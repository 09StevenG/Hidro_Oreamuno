def consultar_servicio(url):
    parametros = {
        "where": "1=1",
        "outFields": "*",
        "returnGeometry": "true",
        "outSR": "5367",
        "f": "geojson"
    }

    respuesta = requests.get(
        url, params=parametros, timeout=120
    )
    respuesta.raise_for_status()

    datos = respuesta.json()

    if "features" not in datos:
        raise ValueError(datos)

    return gpd.GeoDataFrame.from_features(
        datos["features"],
        crs="EPSG:5367"
    )

