import geopandas as gpd
import rasterio
import numpy as np
from pathlib import Path
from rasterio.features import rasterize
from scipy.ndimage import distance_transform_edt

base = Path("/content/GeoAlerta_Oreamuno")

# Cargar red de drenaje
red = gpd.read_file(
    base / "03_Modelos_Hidrologicos/Oreamuno_Red_Drenaje_1000_Completa.gpkg"
)

# Abrir DEM de referencia
ruta_dem = (
    base / "03_Modelos_Hidrologicos/Oreamuno_DEM_Acondicionado.tif"
)

with rasterio.open(ruta_dem) as src:
    perfil = src.profile.copy()
    transform = src.transform
    resolucion_x = abs(transform.a)
    resolucion_y = abs(transform.e)
    mascara_dem = src.read_masks(1) > 0
    alto, ancho = src.height, src.width

# Preparar red en CRS del DEM
red = red.to_crs(perfil["crs"])

# Rasterizar los cauces
red_raster = rasterize(
    [(geom, 1) for geom in red.geometry if geom is not None],
    out_shape=(alto, ancho),
    transform=transform,
    fill=0,
    dtype="uint8",
    all_touched=True
)

# Distancia euclidiana al cauce más cercano
distancia = distance_transform_edt(
    red_raster == 0,
    sampling=(resolucion_y, resolucion_x)
)

# Aplicar máscara del cantón
canton = gpd.read_file(
    base / "01_Datos_Originales/Oreamuno_Canton.gpkg"
).to_crs(perfil["crs"])

from rasterio.features import geometry_mask

mascara_canton = geometry_mask(
    canton.geometry,
    out_shape=(alto, ancho),
    transform=transform,
    invert=True
)

distancia[~mascara_canton] = -9999

# Guardar resultado
perfil.update(
    dtype="float32",
    count=1,
    nodata=-9999,
    compress="lzw"
)

ruta_salida = (
    base / "03_Modelos_Hidrologicos/"
    "Oreamuno_Distancia_Drenaje.tif"
)

with rasterio.open(ruta_salida, "w", **perfil) as dst:
    dst.write(distancia.astype("float32"), 1)

# Estadísticas
valores = distancia[mascara_canton & mascara_dem]

print("DISTANCIA A LA RED DE DRENAJE")
print("=" * 50)

for p in [0, 25, 50, 75, 90, 95, 99, 100]:
    print(f"P{p}: {np.percentile(valores, p):.2f} m")

print("\nRáster guardado en:")
