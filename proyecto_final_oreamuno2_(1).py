def clasificar_cuantiles(arreglo, mascara):
    """
    Clasifica valores continuos en cinco categorías
    mediante los percentiles 20, 40, 60 y 80.
    """
    salida = np.zeros(arreglo.shape, dtype=np.uint8)

    validos = (
        mascara &
        np.isfinite(arreglo) &
        (arreglo > 0)
    )

    valores = arreglo[validos]

    cortes = np.percentile(
        valores,
        [20, 40, 60, 80]
    )

    salida[validos] = (
        np.digitize(valores, cortes) + 1
    ).astype(np.uint8)

    return salida, cortes

