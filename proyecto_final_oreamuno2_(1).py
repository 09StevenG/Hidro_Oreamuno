def _url_tesela(lat, lon, glo=30):
    """Construye la URL de una tesela Copernicus."""

    res = "10" if glo == 30 else "30"

    ns = "N" if lat >= 0 else "S"
    ew = "E" if lon >= 0 else "W"

    nombre = (
        f"Copernicus_DSM_COG_{res}_"
        f"{ns}{abs(lat):02d}_00_"
        f"{ew}{abs(lon):03d}_00_DEM"
    )

    return (
        f"https://copernicus-dem-{glo}m.s3.amazonaws.com/"
        f"{nombre}/{nombre}.tif"
    )


def obtener_dem(lat_min, lon_min, lat_max, lon_max, glo=30):
    """
    Descarga y mosaica las teselas Copernicus.
    Devuelve matriz DEM, transformación y perfil.
    """

    teselas = [
        (la, lo)
        for la in range(math.floor(lat_min),
                        math.floor(lat_max) + 1)
        for lo in range(math.floor(lon_min),
                        math.floor(lon_max) + 1)
    ]

    abiertas = []

    try:
        for la, lo in teselas:

            url = _url_tesela(la, lo, glo)

            print(f"Abriendo tesela: {la}, {lo}")

            abiertas.append(rasterio.open(url))

        mosaico, transform = merge(
            abiertas,
            bounds=(lon_min, lat_min, lon_max, lat_max)
        )

        perfil = abiertas[0].profile.copy()

        perfil.update(
            driver="GTiff",
            count=1,
            height=mosaico.shape[1],
            width=mosaico.shape[2],
            transform=transform
        )

        print(f"\nCopernicus GLO-{glo}")
        print("Teselas utilizadas:", len(teselas))
        print(
            f"Dimensiones: {mosaico.shape[2]} x "
            f"{mosaico.shape[1]} celdas"
        )

        return mosaico[0], transform, perfil

    finally:
        for archivo in abiertas:
            archivo.close()

